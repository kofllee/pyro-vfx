"""Build original 24px Pixelarticons atlas with measured glyph bounds.

24x24 is the SOURCE VIEWBOX, not the actual drawing footprint.
The generated UiIconBounds.java is tightly coupled to the PNG and is intentionally
regenerated when source SVGs change. The game does not require Python at runtime.

Dependencies for asset maintainers only: pillow, resvg_py.
Run: py tools/build_pixelarticons.py
"""
from pathlib import Path
import io, re
from PIL import Image
import resvg_py

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "third_party/pixelarticons/source"
OUTPUT = ROOT / "pyro-ui/src/main/resources/assets/pyro_ui/textures/gui/icons/pixelarticons.png"
METRICS = ROOT / "pyro-ui/src/main/java/net/kofllee/pyroui/UiIconBounds.java"
NAMES = [
    "close", "check", "checkbox", "chevron-down", "chevron-right", "chevron-up",
    "plus", "minus", "settings-cog", "sliders", "folder", "folder-plus",
    "pencil", "refresh", "move", "eye", "play", "pause", "expand", "collapse",
    "menu", "fire"
]
VIEWBOX=24
GUTTER=1
CELL=VIEWBOX+GUTTER*2

def main():
    atlas=Image.new("RGBA",(len(NAMES)*CELL,CELL))
    bounds=[]
    for i,name in enumerate(NAMES):
        svg=(SOURCE/(name+".svg")).read_text(encoding="utf-8")
        header=re.search(r"<svg\b[^>]*>",svg)
        if header is None or not re.search(r'viewBox\s*=\s*["\x27]0 0 24 24["\x27]',header.group(0)):
            raise ValueError(f"Unexpected viewBox for {name}; expected exact 24x24")
        data=resvg_py.svg_to_bytes(svg_string=svg,width=VIEWBOX,height=VIEWBOX)
        image=Image.open(io.BytesIO(data)).convert("RGBA")
        bbox=image.getchannel("A").getbbox()
        if bbox is None:
            raise ValueError("Empty SVG "+name)
        x0,y0,x1,y1=bbox
        bounds.append((x0,y0,x1-x0,y1-y0))
        # This is a tintable white alpha mask. The original SVG inherits
        # currentColor (black in an unstyled SVG rasterizer), and leaving that
        # RGB in the atlas would multiply the UI accent color down to black.
        white=Image.new("RGBA",image.size,(255,255,255,0))
        white.putalpha(image.getchannel("A"))
        # Keep native viewbox coverage, clear gutters and measured ink bounds.
        atlas.alpha_composite(white,(i*CELL+GUTTER,GUTTER))
        print(f"{name:16} glyph={x1-x0:2}x{y1-y0:2} offset={x0:2},{y0:2} viewbox={VIEWBOX}x{VIEWBOX}")
    OUTPUT.parent.mkdir(parents=True,exist_ok=True)
    atlas.save(OUTPUT,optimize=True)
    lines=[
        "package net.kofllee.pyroui;",
        "",
        "/** Generated by tools/build_pixelarticons.py from original MIT Pixelarticons SVGs.",
        " * Each row is [inkX, inkY, inkWidth, inkHeight] in the 24x24 viewbox.",
        " * The artwork's 24x24 viewbox is NOT equivalent to a 24x24 visible glyph.",
        " */",
        "final class UiIconBounds {",
        f"    static final int VIEWBOX = {VIEWBOX};",
        f"    static final int GUTTER = {GUTTER};",
        f"    static final int CELL = {CELL};",
        "    static final String[] NAMES = {",
        *["        \""+name+"\"," for name in NAMES],
        "    };",
        "    static final int[][] INK = {",
        *[f"        {{{x},{y},{w},{h}}}, // {name}" for name,(x,y,w,h) in zip(NAMES,bounds)],
        "    };",
        "    private UiIconBounds() {}",
        "}",
        ""
    ]
    METRICS.parent.mkdir(parents=True,exist_ok=True)
    METRICS.write_text("\n".join(lines),encoding="utf-8")
    print(f"Atlas: {atlas.size[0]}x{atlas.size[1]}, {len(NAMES)} source-aligned icons.")
if __name__=="__main__": main()
